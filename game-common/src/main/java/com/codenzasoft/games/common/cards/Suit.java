package com.codenzasoft.games.common.cards;

/** The four suits of a standard playing-card deck, ordered by Hearts point value (ascending). */
public enum Suit {
  /** Clubs — no point value in Hearts. */
  CLUBS,
  /** Diamonds — no point value in Hearts. */
  DIAMONDS,
  /** Spades — contains the Queen of Spades (13 pts in Hearts). */
  SPADES,
  /** Hearts — each card is worth 1 point in Hearts. */
  HEARTS;
}
